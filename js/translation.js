    // Detectar idioma del texto
    detectLanguage(text) {
        // Detectar si contiene caracteres en inglés comunes
        const englishWords = ['the', 'and', 'or', 'but', 'in', 'on', 'at', 'to', 'for', 'of', 'with', 'by', 'is', 'are', 'was', 'were', 'be', 'been', 'have', 'has', 'had', 'do', 'does', 'did', 'will', 'would', 'could', 'should', 'may', 'might', 'can', 'must'];
        const spanishWords = ['el', 'la', 'los', 'las', 'un', 'una', 'y', 'o', 'pero', 'en', 'de', 'del', 'al', 'con', 'por', 'para', 'es', 'son', 'está', 'están', 'ser', 'estar', 'tener', 'hacer', 'ir', 'venir', 'que', 'qué', 'como', 'cómo'];
        
        const words = text.toLowerCase().split(/\s+/);
        let englishCount = 0;
        let spanishCount = 0;
        
        words.forEach(word => {
            const cleanWord = word.replace(/[.,!?;:]/g, '');
            if (englishWords.includes(cleanWord)) englishCount++;
            if (spanishWords.includes(cleanWord)) spanishCount++;
        });
        
        // Si hay más palabras en inglés, asumir inglés, sino español
        return englishCount > spanishCount ? 'en' : 'es';
    }

    // Traducción usando API externa
    async translateToChineseAPI(text) {
        try {
            // Detectar idioma automáticamente
            const sourceLang = this.detectLanguage(text);
            const response = await fetch(`https://api.mymemory.translated.net/get?q=${encodeURIComponent(text)}&langpair=${sourceLang}|zh-CN`);
            const data = await response.json();
            
            if (data.responseStatus === 200 && data.responseData.translatedText) {
                return data.responseData.translatedText;
            }
        } catch (error) {
            console.log('API translation failed, using local dictionary');
        }
        
        // Fallback al diccionario local
        return this.translateToChineseLocal(text);
    }

    // Traducción usando diccionario local
    translateToChineseLocal(text) {
        if (!text.trim()) return '';
        
        const words = text.toLowerCase().split(/\s+/);
        const translatedWords = words.map(word => {
            // Remover puntuación para la búsqueda
            const cleanWord = word.replace(/[.,!?;:]/g, '');
            return this.multiLanguageToChinese[cleanWord] || word;
        });
        
        return translatedWords.join(' ');
    }

    // Actualizar traducción con debouncing
    async updateTranslation(text) {
        // Inicializar referencia al contenido si no existe
        if (!this.translationContent) {
            this.translationContent = this.translationDisplay.querySelector('.translation-content');
        }
        
        if (!text.trim()) {
            if (this.translationContent) {
                this.translationContent.textContent = '';
            }
            this.translationDisplay.classList.remove('translation-loading');
            return;
        }
        
        // Mostrar indicador de carga
        if (this.translationContent) {
            this.translationContent.textContent = '翻译中...';
        }
        this.translationDisplay.classList.add('translation-loading');
        
        try {
            const translation = await this.translateToChineseAPI(text);
            if (this.translationContent) {
                this.translationContent.textContent = translation;
            }
        } catch (error) {
            const fallbackTranslation = this.translateToChineseLocal(text);
            if (this.translationContent) {
                this.translationContent.textContent = fallbackTranslation;
            }
        } finally {
            this.translationDisplay.classList.remove('translation-loading');
        }
    }

    // Configurar traducción con delay
    setupTranslation(text) {
        clearTimeout(this.translationTimeout);
        this.translationTimeout = setTimeout(() => {
            this.updateTranslation(text);
        }, 500);
    }

    // Obtener traducción inmediata (para historial)
    getImmediateTranslation(text) {
        return this.translateToChineseLocal(text);
    }

    // Obtener traducción para visualización (sin mostrar en el campo de traducción)
    async getTranslationForVisualization(text) {
        if (!text.trim()) {
            return '';
        }
        
        try {
            const translation = await this.translateToChineseAPI(text);
            return translation;
        } catch (error) {
            return this.translateToChineseLocal(text);
        }
    }
